var (
	// Lowercase only: SMB share names are case-insensitive but the backing
	// directories are not.
	repoNameRe    = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,31}$`)
	usernameRe    = regexp.MustCompile(`^[a-z][a-z0-9_-]{0,31}$`)
	reservedNames = map[string]bool{"global": true, "homes": true, "printers": true}
)

func validateRepoName(name string) error {
	if !repoNameRe.MatchString(name) || reservedNames[name] {
		return errors.New("repository name must be 1-32 chars: lowercase letters, digits, '-' or '_', starting with a letter or digit")
	}
	return nil
}

func validateUsername(st *State, name string) error {
	if !usernameRe.MatchString(name) {
		return errors.New("username must be 1-32 chars: lowercase letters, digits, '-' or '_', starting with a letter")
	}
	if _, c := st.Credential(name); c != nil {
		return fmt.Errorf("username %q is already in use", name)
	}
	if _, err := user.Lookup(name); err == nil {
		return fmt.Errorf("username %q is reserved by the system", name)
	}
	return nil
}

func validatePassword(pw string) error {
	if len(pw) < 8 {
		return errors.New("password must be at least 8 characters")
	}
	if strings.ContainsFunc(pw, func(r rune) bool { return r < 0x20 || r == 0x7f }) {
		return errors.New("password must not contain control characters")
	}
	return nil
}

func repoPath(name string) string {
	return filepath.Join(backupsDir, name)
}

func ensureRepoDir(name string) error {
	u, err := user.Lookup(forceUser)
	if err != nil {
		return err
	}
	uid, _ := strconv.Atoi(u.Uid)
	gid, _ := strconv.Atoi(u.Gid)
	p := repoPath(name)
	if err := os.MkdirAll(p, 0o700); err != nil {
		return err
	}
	if err := os.Chown(p, uid, gid); err != nil {
		return err
	}
	return os.Chmod(p, 0o700) //nolint:gosec // directory needs the execute bit
}

func run(stdin string, name string, args ...string) error {
	cmd := exec.Command(name, args...) //nolint:gosec // callers pass fixed program names; args are validated
	cmd.Stdin = strings.NewReader(stdin)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("%s: %w: %s", name, err, bytes.TrimSpace(out))
	}
	return nil
}

// Samba needs a Unix account behind every SMB user. These accounts cannot log
// in and own nothing; files are written as forceUser.
func addSystemUser(c *Credential) error {
	return run("", "useradd", "--no-create-home", "--home-dir", "/nonexistent",
		"--shell", "/usr/sbin/nologin", "--gid", "users", "--uid", strconv.Itoa(c.UID), c.Username)
}

func setSambaPassword(username, password string) error {
	return run(password+"\n"+password+"\n", "smbpasswd", "-s", "-a", username)
}

func deleteUser(username string) error {
	errSmb := run("", "smbpasswd", "-x", username)
	errSys := run("", "userdel", username)
	return errors.Join(errSmb, errSys)
}

func createCredential(st *State, username, password string) (*Credential, error) {
	c := &Credential{Username: username, UID: st.NextUID, Enabled: true}
	if err := addSystemUser(c); err != nil {
		return nil, err
	}
	if err := setSambaPassword(username, password); err != nil {
		if errDel := run("", "userdel", username); errDel != nil {
			log.Printf("rollback user %s: %v", username, errDel) //nolint:gosec // username is validated
		}
		return nil, err
	}
	st.NextUID++
	return c, nil
}

func reconcileUsers(st *State) error {
	for _, r := range st.Repos {
		for _, c := range r.Credentials {
			if _, err := user.Lookup(c.Username); err == nil {
				continue
			}
			if err := addSystemUser(c); err != nil {
				return err
			}
		}
	}
	return nil
}

// closeShare drops existing connections so removed or disabled credentials
// lose access immediately; a config reload only affects new connections.
// Time Machine reconnects on its own.
func closeShare(name string) {
	if err := run("", "smbcontrol", "smbd", "close-share", name); err != nil {
		log.Printf("close share %s: %v", name, err) //nolint:gosec // name is a validated repo name
	}
}

