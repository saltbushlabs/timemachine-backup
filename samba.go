func writeConfigs(st *State) error {
	type share struct {
		Name, Path, Users string
		Available         bool
		QuotaGB           int
	}
	var shares []share
	var advertised []string
	for _, r := range st.Repos {
		users := r.EnabledUsers()
		if len(users) == 0 {
			users = []string{"nobody"} // never leave "valid users" empty
		}
		shares = append(shares, share{
			Name: r.Name, Path: repoPath(r.Name), Users: strings.Join(users, " "),
			Available: r.Available(), QuotaGB: r.QuotaGB,
		})
		if r.Available() {
			advertised = append(advertised, r.Name)
		}
	}
	var smb, avahi bytes.Buffer
	if err := sharesTmpl.Execute(&smb, shares); err != nil {
		return err
	}
	if err := avahiTmpl.Execute(&avahi, advertised); err != nil {
		return err
	}
	if err := writeAtomic(sharesConf, smb.Bytes(), 0o644); err != nil {
		return err
	}
	return writeAtomic(avahiServiceFile, avahi.Bytes(), 0o644)
}
